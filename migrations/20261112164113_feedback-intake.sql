CREATE TABLE public.feedback_submissions (
  id uuid PRIMARY KEY,
  payload_hash text NOT NULL,
  state text NOT NULL CHECK (state IN ('pending', 'uncertain', 'created')),
  created_at timestamptz NOT NULL DEFAULT now(),
  issue_number integer,
  issue_url text
);
CREATE TABLE public.feedback_limits (
  bucket text PRIMARY KEY,
  hits integer NOT NULL,
  expires_at timestamptz NOT NULL
);
ALTER TABLE public.feedback_submissions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.feedback_limits ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.feedback_submissions, public.feedback_limits FROM PUBLIC, anon, authenticated;

CREATE FUNCTION public.feedback_claim(p_id uuid, p_hash text, p_client text)
RETURNS jsonb LANGUAGE plpgsql SET search_path = public, pg_temp AS $$
DECLARE r public.feedback_submissions; n integer; k text; t timestamptz := now();
BEGIN
  -- Serialize admission, quotas and UUID claims across all function instances.
  PERFORM pg_advisory_xact_lock(5715580, 1);
  DELETE FROM public.feedback_limits WHERE expires_at < t;
  DELETE FROM public.feedback_submissions WHERE created_at < t - interval '7 days';
  k := 'probe:' || p_client || ':' || floor(extract(epoch FROM t)/600)::text;
  INSERT INTO public.feedback_limits VALUES(k, 1, t + interval '24 hours')
    ON CONFLICT(bucket) DO UPDATE SET hits = feedback_limits.hits + 1 RETURNING hits INTO n;
  IF n > 60 THEN RETURN jsonb_build_object('status',429,'retryAfter',600); END IF;
  SELECT * INTO r FROM public.feedback_submissions WHERE id = p_id;
  IF FOUND THEN
    IF r.payload_hash <> p_hash THEN RETURN jsonb_build_object('status',409); END IF;
    IF r.state = 'created' THEN RETURN jsonb_build_object('status',200,'issueNumber',r.issue_number,'issueUrl',r.issue_url); END IF;
    IF r.state = 'pending' THEN
      UPDATE public.feedback_submissions SET state = 'uncertain' WHERE id = p_id;
      RETURN jsonb_build_object('status',201,'dispatch',true);
    END IF;
    RETURN jsonb_build_object('status',202,'createdAt',r.created_at);
  END IF;
  -- UUIDv7 is generated by the client. Reject IDs older than the retention window.
  IF ('x' || substr(replace(p_id::text,'-',''),1,12))::bit(48)::bigint < (extract(epoch FROM t - interval '7 days')*1000)::bigint
    THEN RETURN jsonb_build_object('status',409); END IF;
  k := 'day:' || to_char(t AT TIME ZONE 'UTC','YYYY-MM-DD');
  SELECT hits INTO n FROM public.feedback_limits WHERE bucket=k;
  IF coalesce(n,0) >= 100 THEN RETURN jsonb_build_object('status',429,'retryAfter',86400); END IF;
  k := 'new:' || p_client || ':' || floor(extract(epoch FROM t)/600)::text;
  SELECT hits INTO n FROM public.feedback_limits WHERE bucket=k;
  IF coalesce(n,0) >= 5 THEN RETURN jsonb_build_object('status',429,'retryAfter',600); END IF;
  INSERT INTO public.feedback_limits VALUES(k,1,t+interval '24 hours')
    ON CONFLICT(bucket) DO UPDATE SET hits=feedback_limits.hits+1;
  k := 'day:' || to_char(t AT TIME ZONE 'UTC','YYYY-MM-DD');
  INSERT INTO public.feedback_limits VALUES(k,1,t+interval '24 hours')
    ON CONFLICT(bucket) DO UPDATE SET hits=feedback_limits.hits+1;
  INSERT INTO public.feedback_submissions(id,payload_hash,state) VALUES(p_id,p_hash,'uncertain');
  RETURN jsonb_build_object('status',201,'dispatch',true);
END $$;

CREATE FUNCTION public.feedback_complete(p_id uuid, p_number integer DEFAULT NULL, p_url text DEFAULT NULL)
RETURNS void LANGUAGE sql SET search_path = public, pg_temp AS $$
  UPDATE public.feedback_submissions
  SET state = CASE WHEN p_number IS NULL THEN 'pending' ELSE 'created' END,
      issue_number = p_number, issue_url = p_url
  WHERE id=p_id AND state <> 'created';
$$;
REVOKE ALL ON FUNCTION public.feedback_claim(uuid,text,text) FROM PUBLIC, anon, authenticated;
REVOKE ALL ON FUNCTION public.feedback_complete(uuid,integer,text) FROM PUBLIC, anon, authenticated;
